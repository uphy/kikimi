    // MARK: - Ordering determinism (design §3.1 "Line.id を持つ理由")

    @Test("render(_:scope:) orders same-startMs lines by id ascending regardless of input order")
    func renderOrdersSameStartMsLinesByIdAscending() {
        let meta = makeMeta()
        let forward = [
            makeLine(id: "a", startMs: 1_000, speakerName: "自分", text: "first"),
            makeLine(id: "b", startMs: 1_000, speakerName: "田中", text: "second"),
        ]
        let reversed = Array(forward.reversed())

        let forwardMarkdown = TranscriptMarkdownRenderer.render(
            TranscriptMarkdownRenderer.Input(meta: meta, summaryMarkdown: "", lines: forward), scope: .transcript
        )
        let reversedMarkdown = TranscriptMarkdownRenderer.render(
            TranscriptMarkdownRenderer.Input(meta: meta, summaryMarkdown: "", lines: reversed), scope: .transcript
