        #expect(forwardMarkdown == reversedMarkdown)
        #expect(forwardMarkdown.contains("first"))
        let firstRange = forwardMarkdown.range(of: "first")
        let secondRange = forwardMarkdown.range(of: "second")
        #expect(firstRange != nil && secondRange != nil && firstRange!.lowerBound < secondRange!.lowerBound)
    }

