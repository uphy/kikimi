/// Layer 1 (unit) coverage for `TranscriptMarkdownRenderer` (`docs/design/37-transcript-markdown-copy
/// .md` §3.1/§4/§7), the pure rendering half shared by the Wiki export and the "copy transcript as
/// Markdown" feature. Every test constructs plain `Input`/`Line` values directly -- never a
/// `SessionHandle`/`AppConfig` -- since speaker-name resolution and line selection are each caller's
/// adapter's job (design §3.2), not this type's.
///
/// Every `Date` fixture is built from `DateComponents` against `Calendar.current`/`TimeZone.current`
/// (via `date(...)` below), matching the renderer's own `.current`-timezone formatters, so assertions
/// never depend on which timezone actually runs the test.
@Suite("TranscriptMarkdownRenderer")
struct TranscriptMarkdownRendererTests {
    /// `static` (not an instance method) so it can also be used directly in another helper's default
    /// argument expressions (`makeMeta(...)`'s `createdAt`/`startedAt` defaults below), which run in a
    /// context with no `self`.
    private static func date(year: Int, month: Int, day: Int, hour: Int, minute: Int, second: Int) -> Date {
        var calendar = Calendar(identifier: .gregorian)
        calendar.timeZone = .current
        var components = DateComponents()
        components.year = year
        components.month = month
        components.day = day
        components.hour = hour
        components.minute = minute
        components.second = second
        return calendar.date(from: components)!
    }

    /// - Parameter startedAt: Passed straight through to `SessionMeta.startedAt` with **no**
    ///   `?? fallback` substitution -- its default argument value is already the sensible non-nil
    ///   date most tests want, so a test that instead needs `meta.startedAt == nil` can pass
    ///   `startedAt: nil` explicitly and have it actually land on the constructed `SessionMeta`.
    private func makeMeta(
        id: String = "2026-07-01T14-30-00_a1b2c3d4",
        title: String = "デイリースクラム",
        createdAt: Date = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 28, second: 12),
        startedAt: Date? = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0),
        durationMs: Int = 2_722_000,
        recordings: [RecordingSegment] = []
    ) -> SessionMeta {
        SessionMeta(
            id: id,
            title: title,
            titleAutoGenerated: true,
            titleAutoNamedOnce: true,
            titleProposal: nil,
            state: .ended,
            createdAt: createdAt,
            startedAt: startedAt,
            endedAt: Self.date(year: 2_026, month: 7, day: 1, hour: 15, minute: 15, second: 22),
            durationMs: durationMs,
            recordings: recordings,
            basedOnSession: nil,
            segmentCount: 0,
            refinedCount: 0,
            appVersion: "0.1.0"
        )
    }

    private func makeLine(
        id: String,
        startMs: Int,
        speakerName: String = "田中",
        text: String = "テキスト",
        isRawFallback: Bool = false
    ) -> TranscriptMarkdownRenderer.Line {
        TranscriptMarkdownRenderer.Line(id: id, startMs: startMs, speakerName: speakerName, text: text, isRawFallback: isRawFallback)
    }

    // MARK: - wallClockDate(startMs:recordings:fallback:)

    @Test("wallClockDate resolves a single-segment session's startMs directly against its startedAt")
    func wallClockDateSingleSegment() {
        let started = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0)
        let recordings = [RecordingSegment(index: 0, startedAt: started, endedAt: nil, startMsOffset: 0)]
        let result = TranscriptMarkdownRenderer.wallClockDate(startMs: 5_000, recordings: recordings, fallback: started)
        #expect(result == started.addingTimeInterval(5))
    }

    @Test("wallClockDate resolves a startMs in the second of two recording segments (a pause/resume gap)")
    func wallClockDateAcrossTwoSegments() {
        let firstStart = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0)
        let secondStart = Self.date(year: 2_026, month: 7, day: 1, hour: 15, minute: 5, second: 30)
        let recordings = [
            RecordingSegment(index: 0, startedAt: firstStart, endedAt: firstStart.addingTimeInterval(1_330), startMsOffset: 0),
            RecordingSegment(index: 1, startedAt: secondStart, endedAt: nil, startMsOffset: 1_330_000),
        ]
        // 10 seconds into the second segment.
        let result = TranscriptMarkdownRenderer.wallClockDate(startMs: 1_340_000, recordings: recordings, fallback: firstStart)
        #expect(result == secondStart.addingTimeInterval(10))
    }

    @Test("wallClockDate at exactly a segment boundary offset resolves to that segment's startedAt")
    func wallClockDateAtExactSegmentBoundary() {
        let firstStart = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0)
        let secondStart = Self.date(year: 2_026, month: 7, day: 1, hour: 15, minute: 5, second: 30)
        let recordings = [
            RecordingSegment(index: 0, startedAt: firstStart, endedAt: firstStart.addingTimeInterval(1_330), startMsOffset: 0),
            RecordingSegment(index: 1, startedAt: secondStart, endedAt: nil, startMsOffset: 1_330_000),
        ]
        let result = TranscriptMarkdownRenderer.wallClockDate(startMs: 1_330_000, recordings: recordings, fallback: firstStart)
        #expect(result == secondStart)
    }

    @Test("wallClockDate resolves a startMs owned by the middle of three recording segments, not just the last")
    func wallClockDateAmongThreeSegmentsPicksTheOwningSegment() {
        // Regression for the doc comment's "the one with the greatest startMsOffset <= startMs":
        // every other wallClockDate test above uses at most two segments, where `last(where:)` and a
        // naive "always use recordings.last" bug would coincidentally produce the same answer. A
        // startMs that lands inside the *middle* segment (neither the first nor the last) is the only
        // way to catch that class of bug directly.
        let firstStart = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0)
        let secondStart = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 45, second: 0)
        let thirdStart = Self.date(year: 2_026, month: 7, day: 1, hour: 15, minute: 10, second: 0)
        let recordings = [
            RecordingSegment(index: 0, startedAt: firstStart, endedAt: firstStart.addingTimeInterval(600), startMsOffset: 0),
            RecordingSegment(index: 1, startedAt: secondStart, endedAt: secondStart.addingTimeInterval(600), startMsOffset: 600_000),
            RecordingSegment(index: 2, startedAt: thirdStart, endedAt: nil, startMsOffset: 1_200_000),
        ]
        // 100 seconds into the second (middle) segment -- well before the third segment's offset.
        let result = TranscriptMarkdownRenderer.wallClockDate(startMs: 700_000, recordings: recordings, fallback: firstStart)
        #expect(result == secondStart.addingTimeInterval(100))
    }

    @Test("wallClockDate falls back to fallback + startMs when recordings is empty")
    func wallClockDateFallsBackWhenRecordingsIsEmpty() {
        let fallback = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0)
        let result = TranscriptMarkdownRenderer.wallClockDate(startMs: 2_500, recordings: [], fallback: fallback)
        #expect(result == fallback.addingTimeInterval(2.5))
    }

    @Test("wallClockDate falls back to recordings.first (not fallback) when startMs precedes every segment's offset")
    func wallClockDateFallsBackToFirstRecordingWhenStartMsPrecedesAllOffsets() {
        // Defensive-only branch (`last(where:)` finds no match): `startMsOffset` is normally 0 for the
        // first segment, but the guard's `?? recordings.first` still needs to be exercised directly.
        let segmentStart = Self.date(year: 2_026, month: 7, day: 1, hour: 14, minute: 30, second: 0)
        let recordings = [RecordingSegment(index: 0, startedAt: segmentStart, endedAt: nil, startMsOffset: 5_000)]
        let unrelatedFallback = Self.date(year: 2_020, month: 1, day: 1, hour: 0, minute: 0, second: 0)
        let result = TranscriptMarkdownRenderer.wallClockDate(startMs: 1_000, recordings: recordings, fallback: unrelatedFallback)
        // elapsedInSegment = (1_000 - 5_000) / 1_000 = -4s against the *segment's* startedAt, never the fallback.
        #expect(result == segmentStart.addingTimeInterval(-4))
    }

