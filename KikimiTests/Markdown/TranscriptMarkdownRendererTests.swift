    @Test("render(_:scope: .full) uses createdAt for both the frontmatter date and the transcript wall-clock when startedAt is nil")
    func renderFullUsesCreatedAtConsistentlyForFrontmatterAndTranscriptWhenStartedAtIsNil() {
        // `referenceDate(for:)`'s doc comment claims the frontmatter `date:` and the transcript's
        // wall-clock fallback "always agree even for a degenerate session with no recordings at all" --
        // but `render(_:scope:)` calls `referenceDate(for: meta)` from two independent call sites
        // (`frontmatterBlock` and the transcript body), so nothing structurally guarantees that beyond
        // both happening to call the same pure function. Every other `render` test uses a non-nil
        // `startedAt`, which never exercises this fallback path at all.
        let created = Self.date(year: 2_026, month: 8, day: 15, hour: 9, minute: 0, second: 0)
        let meta = makeMeta(title: "無題の会議", createdAt: created, startedAt: nil, recordings: [])
        let lines = [makeLine(id: "seg_00001", startMs: 5_000, speakerName: "自分", text: "本文です。")]

        let markdown = TranscriptMarkdownRenderer.render(
            TranscriptMarkdownRenderer.Input(meta: meta, summaryMarkdown: "", lines: lines),
            scope: .full
        )

        #expect(markdown.contains("date: 2026-08-15"))
        // 5 seconds after createdAt (09:00:00), the same reference point the frontmatter date used.
        #expect(markdown.contains("**09:00:05 自分** 本文です。"))
    }

    @Test("render(_:scope:) treats a whitespace-only summaryMarkdown as non-empty (no trimming before the isEmpty check)")
    func renderTreatsWhitespaceOnlySummaryMarkdownAsNonEmpty() {
        // TC14 only specifies that an empty string ("") omits the heading; the implementation's
        // `!input.summaryMarkdown.isEmpty` check is a literal string comparison with no trimming, so a
        // whitespace-only string is *not* empty and must still produce the heading. This pins that
        // literal (non-trimmed) contract against a future "helpful" trim being added.
        let meta = makeMeta(title: "空白サマリの会議")
        let markdown = TranscriptMarkdownRenderer.render(
            TranscriptMarkdownRenderer.Input(meta: meta, summaryMarkdown: "   ", lines: []),
            scope: .summary
        )
        #expect(markdown.contains("## サマリ"))
        #expect(markdown == "# 空白サマリの会議\n\n## サマリ\n\n   \n")
    }

    @Test("render(_:scope:) passes a title containing Markdown-sensitive characters through verbatim, unescaped")
    func renderPassesThroughMarkdownSensitiveTitleUnescaped() {
        // The renderer documents itself as purely ordering/formatting already-final strings (type doc
        // comment, lines 12-15) -- it has no escaping step. A title containing `#`/`*`/`[]` (a real
        // possibility for an auto-generated or user-edited meeting title) must appear byte-for-byte
        // after "# ", not be sanitized or corrupt the heading.
        let meta = makeMeta(title: "# 顧客A [緊急] *打ち合わせ*")
        let markdown = TranscriptMarkdownRenderer.render(
            TranscriptMarkdownRenderer.Input(meta: meta, summaryMarkdown: "", lines: []),
            scope: .transcript
        )
        #expect(markdown == "# # 顧客A [緊急] *打ち合わせ*\n")
    }

