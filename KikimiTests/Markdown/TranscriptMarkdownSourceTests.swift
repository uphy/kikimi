    // MARK: - (a) refined + raw merge (TC15)

    @Test("load merges refined segments with a raw tail segment not covered by any RefinedSegment.sourceSegIds")
    func loadMergesRefinedAndRawTail() async throws {
        let sessionDir = makeTemporaryDirectory(prefix: "TranscriptMarkdownSourceTests-a")
        defer { try? FileManager.default.removeItem(at: sessionDir) }
        let handle = makeSessionHandle(directory: sessionDir)

        let first = try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 1_000, text: "raw one", confidence: 0.9)
        let second = try await handle.appendTranscriptSegment(
            source: .system, startMs: 1_000, endMs: 2_000, text: "raw two (tail)", confidence: 0.9
        )
        try await handle.appendRefinedSegment(
            makeRefinedSegment(id: first.id, startMs: first.startMs, endMs: first.endMs, speaker: .mic, rawText: first.text, refinedText: "整形済みテキスト")
        )
        // `second` is deliberately never refined -- an in-progress recording's tail or a
        // crash-recovery session whose last batch never got refined (TC15).

        let (voiceprintStore, voiceprintFileURL) = makeVoiceprintStore()
        defer { try? FileManager.default.removeItem(at: voiceprintFileURL) }
        let source = makeSource(voiceprintStore: voiceprintStore)

        let input = try await source.load(sessionHandle: handle)

        #expect(input.lines.count == 2)
        let refinedLine = try #require(line(input.lines, id: first.id))
        #expect(refinedLine.text == "整形済みテキスト")
        #expect(refinedLine.isRawFallback == false)

        let tailLine = try #require(line(input.lines, id: second.id))
        #expect(tailLine.text == "raw two (tail)")
        #expect(tailLine.isRawFallback == true)

        // Regression guard for the marker-doubling bug: the raw-fallback marker must appear exactly
        // once in the final rendered output, appended by `TranscriptMarkdownRenderer` from
        // `isRawFallback` alone -- never embedded in `Line.text` by this adapter.
        let rendered = TranscriptMarkdownRenderer.render(input, scope: .transcript)
        let occurrences = rendered.components(separatedBy: TranscriptMarkdownRenderer.rawFallbackMarker).count - 1
        #expect(occurrences == 1)
    }

