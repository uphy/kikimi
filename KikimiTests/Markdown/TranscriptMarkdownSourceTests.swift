    private func makeVoiceprintStore() -> (store: VoiceprintStore, fileURL: URL) {
        let fileURL = FileManager.default.temporaryDirectory
            .appendingPathComponent("TranscriptMarkdownSourceTests-voiceprints-\(UUID().uuidString).json")
        return (VoiceprintStore(fileURL: fileURL), fileURL)
    }

