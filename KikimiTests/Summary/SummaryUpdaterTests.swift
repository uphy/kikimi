    @Test("mergeParticipants with every name already present is a silent no-op: no write, no event")
    func mergeParticipantsAllAlreadyPresentIsNoOp() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = makeHandle(directory: directory, meta: baseMeta())
        try await handle.writeJSON(
            SummaryState(title: nil, participants: ["田中さん"], overview: "既存概要", decisions: [], actionItems: [], lastSummarizedStartMs: 1_000),
            to: .summaryState
        )

        let fakeLLM = FakeLLM()
        let updater = SummaryUpdater(sessionHandle: handle, llm: fakeLLM)
        var eventsIterator = updater.events.makeAsyncIterator()

        await updater.mergeParticipants(["田中さん"])

        // No event fired -- nothing changed, so `mergeParticipants` returns without ever writing to
        // `eventsContinuation`. Prove no event arrived (rather than blocking forever waiting for one)
        // by racing against a manual update, whose event is guaranteed to arrive (startMs must be
        // past the seeded state's lastSummarizedStartMs=1000 cursor, or this segment would itself be
        // filtered out as already-summarized and never produce an event either).
        await fakeLLM.setResponse(emptyPatchJSON, for: "summary_patch")
        try await appendSegments(1, to: handle, startingAt: 2_000)
        await updater.updateNow(reason: .manual)
        let firstEvent = try #require(await eventsIterator.next())
        #expect(firstEvent.summaryMarkdown != nil) // this is the manual update's event, not a merge event

        let state = try #require(try await handle.readJSON(.summaryState, as: SummaryState.self))
        #expect(state.participants == ["田中さん"]) // unchanged by the no-op merge
        #expect(state.overview == "既存概要") // untouched by the no-op merge, then untouched by the empty patch
        // The cursor did advance -- but only because of the manual update that followed, proving the
        // no-op merge itself never touched anything (it ran first, against the still-1_000 cursor).
        #expect(state.lastSummarizedStartMs == 2_000)
    }

