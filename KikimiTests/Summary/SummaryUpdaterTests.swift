// MARK: - FakeLLM

/// Deterministic, network-free stand-in for `LLMCompleting` (`docs/design/04-summary-updater.md`
/// §4.1's SWE review C8: inject the narrow seam, not the concrete `LLMClient`). An `actor` so
/// call-count/received-request assertions are race-free, mirroring `LLMClientTests.swift`'s
/// `FakeProcessRunner`.
///
/// Responses are registered per `stubKey` as raw JSON strings and decoded into whatever `T` the
/// caller asks for -- this mirrors `LLMStubProvider`'s own dispatch-by-`stubKey` shape closely
/// enough that the fixtures read the same way.
private actor FakeLLM: LLMCompleting {
    private(set) var callCount = 0
    private(set) var receivedRequests: [LLMRequest] = []

    /// `stubKey -> raw JSON`. A missing key throws `.missingStructuredOutput`, matching
    /// `LLMStubProvider`'s own safe-default behavior.
    var responses: [String: String] = [:]
    /// `stubKey -> error` overrides `responses` when both are set for the same key.
    var errors: [String: LLMClientError] = [:]

    func complete<T: Decodable & Sendable>(_ request: LLMRequest) async throws -> LLMResult<T> {
        let data = try resolveData(for: request)
        // Mirror `LLMClient.decodeResult`'s `.convertFromSnakeCase` decoding of `structured_output`
        // so snake_case fixture keys (`decisions_add`/`source_seg_ids`/...) map onto the camelCase
        // `SummaryPatch`/`SummaryState` properties exactly as they would in production.
        let decoder = JSONDecoder()
        decoder.keyDecodingStrategy = .convertFromSnakeCase
        let value = try decoder.decode(T.self, from: data)
        return LLMResult(value: value, usage: .zero)
    }

    /// `docs/design/05-watcher-runner.md` §5.1: not exercised by any `SummaryUpdater` test in this
    /// file, but required to satisfy `LLMCompleting`.
    func completeRaw(_ request: LLMRequest) async throws -> LLMResult<Data> {
        LLMResult(value: try resolveData(for: request), usage: .zero)
    }

    private func resolveData(for request: LLMRequest) throws -> Data {
        callCount += 1
        receivedRequests.append(request)
        let key = request.stubKey ?? ""
        if let error = errors[key] {
            throw error
        }
        guard let rawJSON = responses[key], let data = rawJSON.data(using: .utf8) else {
            throw LLMClientError.missingStructuredOutput(raw: "no fake response for stubKey=\(key)")
        }
        return data
    }
}

