    @Test("cursor uses strict > so a segment with startMs equal to the cursor is not re-included")
    func cursorUsesStrictGreaterThan() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = makeHandle(directory: directory, meta: baseMeta())
        // Two segments sharing the same startMs (mic/system same-timestamp collision, §4.2's C10).
        _ = try await handle.appendTranscriptSegment(source: .mic, startMs: 1_000, endMs: 1_500, text: "first", confidence: 0.9)

        let fakeLLM = FakeLLM()
        await fakeLLM.setResponse(emptyPatchJSON, for: "summary_patch")
        let updater = SummaryUpdater(sessionHandle: handle, llm: fakeLLM)
        await updater.updateNow(reason: .manual)
        #expect(await fakeLLM.callCount == 1)

        // A second segment at the exact same startMs=1000 arrives after the cursor was set to 1000.
        _ = try await handle.appendTranscriptSegment(source: .system, startMs: 1_000, endMs: 1_500, text: "same-time-collision", confidence: 0.9)
        await updater.updateNow(reason: .manual)

        // Documenting current (accepted) behavior: the same-startMs segment is dropped because the
        // cursor comparison is strict `>` (04-summary-updater.md §4.2's "等値 startMs の境界" caveat).
        #expect(await fakeLLM.callCount == 1)
    }

    @Test("loadPendingInput resolves a merged unit's non-leading source_seg_id to the same (already-refined) unit, not a raw fallback (§15.2.5)")
    func loadPendingInputExpandsMergedSourceSegIds() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = makeHandle(directory: directory, meta: baseMeta())
        let segments = try await appendSegments(2, to: handle, textPrefix: "raw")

        // One merged derived unit covering both raw segments -- segments[1]'s own id never appears
        // as a top-level `id` in refined.jsonl, only inside `source_seg_ids` (§15.2.1).
        let mergedUnit = RefinedSegment(
            id: segments[0].id,
            startMs: segments[0].startMs,
            endMs: segments[1].endMs,
            speaker: .mic,
            rawText: "raw 0raw 1",
            refinedText: "整形済み結合テキスト",
            error: nil,
            refinedAt: Date(timeIntervalSince1970: 1_751_000_020),
            model: "claude-haiku-4-5-20251001",
            batchId: "batch_00001",
            sourceSegIds: [segments[0].id, segments[1].id]
        )
        try await handle.appendRefinedSegment(mergedUnit)

        let fakeLLM = FakeLLM()
        await fakeLLM.setResponse(emptyPatchJSON, for: "summary_patch")
        let config = SummaryConfig(updateTriggerSegments: 2, updateTriggerSeconds: 999)
        let updater = SummaryUpdater(sessionHandle: handle, llm: fakeLLM, config: config)
        await updater.noteSegmentAppended()
        await updater.noteSegmentAppended()

        try await waitUntil { await fakeLLM.callCount >= 1 }

        let request = try #require(await fakeLLM.receivedRequests.first)
        #expect(request.user.contains("整形済み結合テキスト"), "both raw segments must resolve to the merged unit's refined text")
        #expect(!request.user.contains("raw 1"), "segments[1] (covered, non-leading) must not fall back to its own raw text")
    }

    @Test("a duplicate refined id in refined.jsonl does not crash loadPendingInput and the later row wins")
    func loadPendingInputToleratesDuplicateRefinedIdLastRowWins() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = makeHandle(directory: directory, meta: baseMeta())
        try await appendSegments(1, to: handle, startingAt: 1_000, stepMs: 500)

        // Simulate a hand-edited / doubly-appended refined.jsonl: two rows share the same seg id
        // (03-refinement-batch.md §3.2's "防御の二重化" — `RefinementQueue`'s `knownIds` set is
        // supposed to prevent this from ever happening via the normal write path, but
        // `loadPendingInput()` must still degrade gracefully rather than trap via
        // `Dictionary(uniqueKeysWithValues:)` if it does).
        try await handle.appendRefinedSegment(makeRefinedSegment(id: "seg_00001", startMs: 1_000, refinedText: "古い整形結果"))
        try await handle.appendRefinedSegment(makeRefinedSegment(id: "seg_00001", startMs: 1_000, refinedText: "新しい整形結果"))

        let fakeLLM = FakeLLM()
        await fakeLLM.setResponse(emptyPatchJSON, for: "summary_patch")
        let updater = SummaryUpdater(sessionHandle: handle, llm: fakeLLM)

        // Must not crash / trap.
        await updater.updateNow(reason: .manual)

        #expect(await fakeLLM.callCount == 1)
        let sentUserPrompt = await fakeLLM.receivedRequests.first?.user
        #expect(sentUserPrompt?.contains("新しい整形結果") == true)
        #expect(sentUserPrompt?.contains("古い整形結果") == false)
    }

