    }

    // MARK: - Helpers

    /// Polls `predicate` on a short interval until it returns `true` or a timeout elapses, since
    /// `noteSegmentAppended`'s auto-triggered update runs on a detached `Task` rather than being
    /// directly awaitable.
    private func waitUntil(
        timeout: Duration = .seconds(10),
        predicate: @escaping () async -> Bool
    ) async throws {
        let deadline = ContinuousClock.now + timeout
        while ContinuousClock.now < deadline {
            if await predicate() { return }
            try await Task.sleep(for: .milliseconds(20))
        }
        #expect(await predicate(), "condition did not become true within \(timeout)")
    }
