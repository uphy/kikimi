    @Test("concurrent manual and threshold-triggered updates do not lose updates or double-apply a patch")
    func concurrentUpdatesDoNotRaceOrDoubleApply() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = makeHandle(directory: directory, meta: baseMeta())
        try await appendSegments(20, to: handle)

        let fakeLLM = FakeLLM()
        await fakeLLM.setResponse(#"""
        {"title":null,"participants_add":null,"overview":null,"decisions_add":[{"text":"決定A","source_seg_ids":["seg_00001"]}],"action_items":null}
        """#, for: "summary_patch")

        let updater = SummaryUpdater(sessionHandle: handle, llm: fakeLLM, config: SummaryConfig(updateTriggerSegments: 20))

        // Interleave a threshold trigger (via noteSegmentAppended) with concurrent manual calls.
        await withTaskGroup(of: Void.self) { group in
            group.addTask { await updater.updateNow(reason: .manual) }
            group.addTask { await updater.updateNow(reason: .manual) }
            group.addTask { await updater.updateNow(reason: .manual) }
        }

        let state = try #require(try await handle.readJSON(.summaryState, as: SummaryState.self))
        // The same decision text must not be duplicated even though multiple update calls raced
        // (applyPatch's own de-duplication, exercised end-to-end through the serialized updater).
        #expect(state.decisions.count == 1)
        #expect(state.decisions.first?.text == "決定A")
    }

