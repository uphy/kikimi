    /// Appends `count` transcript segments (500ms apart, starting at `startingAt`), alternating
    /// mic/system, to `handle`'s `transcript.jsonl`.
    @discardableResult
    private func appendSegments(
        _ count: Int,
        to handle: SessionHandle,
        startingAt: Int = 0,
        stepMs: Int = 500,
        textPrefix: String = "segment"
    ) async throws -> [TranscriptSegment] {
        var results: [TranscriptSegment] = []
        for index in 0..<count {
            let startMs = startingAt + index * stepMs
            let segment = try await handle.appendTranscriptSegment(
                source: index.isMultiple(of: 2) ? .mic : .system,
                startMs: startMs,
                endMs: startMs + stepMs,
                text: "\(textPrefix) \(index)",
                confidence: 0.9
            )
            results.append(segment)
        }
        return results
    }

    /// Mirrors `SessionHandleTranscriptTests.swift`'s helper of the same name: builds a
