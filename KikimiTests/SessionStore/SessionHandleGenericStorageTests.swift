import Foundation
import Testing

@testable import Kikimi

/// Unit tests for `SessionHandle+GenericStorage.swift` (`docs/design/07-session-store.md` section 11 /
/// kikimi.md 8 章・9 章).
///
/// `SessionHandle` is constructed directly via its own `init(directoryURL:meta:...)` (documented as
/// "injectable for testability" in `docs/design/07-session-store.md` section 5.2), rather than going
/// through `SessionStore`, so these tests only depend on `SessionHandle`'s own surface.
@Suite("SessionHandle+GenericStorage")
struct SessionHandleGenericStorageTests {
    private struct SampleState: Codable, Equatable {
        var count: Int
        var label: String
    }

    private func makeSessionDirectory() -> URL {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("SessionHandleGenericStorageTests-\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    private func makeHandle(directoryURL: URL, id: String = "session-a") -> SessionHandle {
        let meta = SessionMeta(
            id: id,
            title: "Test Session",
            titleAutoGenerated: true,
            titleAutoNamedOnce: false,
            titleProposal: nil,
            state: .draft,
            createdAt: Date(timeIntervalSince1970: 1_751_000_000),
            startedAt: nil,
            endedAt: nil,
            durationMs: 0,
            basedOnSession: nil,
            segmentCount: 0,
            refinedCount: 0,
            appVersion: "0.1.0"
        )
        return SessionHandle(directoryURL: directoryURL, meta: meta)
    }

    // MARK: - readJSON / writeJSON

    @Test("readJSON returns nil when summary.state.json does not exist")
    func readJSONReturnsNilWhenMissing() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let result = try await handle.readJSON(.summaryState, as: SampleState.self)
        #expect(result == nil)
    }

    @Test("readJSON returns nil when a watcher's state.json does not exist")
    func readJSONReturnsNilForMissingWatcherState() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let result = try await handle.readJSON(.watcherState(id: "pre-check"), as: SampleState.self)
        #expect(result == nil)
    }

    @Test("writeJSON then readJSON round-trips the exact value for summary.state.json")
    func writeThenReadJSONRoundTripsSummaryState() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let value = SampleState(count: 3, label: "hello")
        try await handle.writeJSON(value, to: .summaryState)

        let readBack = try await handle.readJSON(.summaryState, as: SampleState.self)
        #expect(readBack == value)
        #expect(FileManager.default.fileExists(atPath: root.appendingPathComponent("summary.state.json").path))
    }

    @Test("writeJSON writes watchers/<id>.state.json under the watchers subdirectory")
    func writeJSONResolvesWatcherStatePath() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let value = SampleState(count: 1, label: "pre-check")
        try await handle.writeJSON(value, to: .watcherState(id: "pre-check"))

        let expectedURL = root.appendingPathComponent("watchers/pre-check.state.json")
        #expect(FileManager.default.fileExists(atPath: expectedURL.path))
        let readBack = try await handle.readJSON(.watcherState(id: "pre-check"), as: SampleState.self)
        #expect(readBack == value)
    }

    @Test("writeJSON overwrites rather than appends")
    func writeJSONOverwritesRatherThanAppends() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        try await handle.writeJSON(SampleState(count: 1, label: "first"), to: .summaryState)
        try await handle.writeJSON(SampleState(count: 2, label: "second"), to: .summaryState)

        let readBack = try await handle.readJSON(.summaryState, as: SampleState.self)
        #expect(readBack == SampleState(count: 2, label: "second"))

        // The file itself should contain only the second value's JSON, not both concatenated.
        let raw = try String(contentsOf: root.appendingPathComponent("summary.state.json"), encoding: .utf8)
        #expect(raw.contains("second"))
        #expect(!raw.contains("first"))
    }

    // MARK: - readText / writeText

    @Test("readText returns nil when summary.md does not exist")
    func readTextReturnsNilWhenMissing() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let result = try await handle.readText(.summaryMarkdown)
        #expect(result == nil)
    }

    @Test("writeText then readText round-trips the exact content for summary.md")
    func writeThenReadTextRoundTripsSummaryMarkdown() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let content = "# デイリースクラム\n\n## 概要\n\nテスト内容"
        try await handle.writeText(content, to: .summaryMarkdown)

        #expect(try await handle.readText(.summaryMarkdown) == content)
        let raw = try String(contentsOf: root.appendingPathComponent("summary.md"), encoding: .utf8)
        #expect(raw == content)
    }

    @Test("writeText writes watchers/<id>.md under the watchers subdirectory")
    func writeTextResolvesWatcherDefinitionPath() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let content = "---\nid: pre-check\n---\n# System\n"
        try await handle.writeText(content, to: .watcherDefinition(id: "pre-check"))

        let expectedURL = root.appendingPathComponent("watchers/pre-check.md")
        #expect(FileManager.default.fileExists(atPath: expectedURL.path))
        #expect(try await handle.readText(.watcherDefinition(id: "pre-check")) == content)
    }

    @Test("writeText overwrites rather than appends")
    func writeTextOverwritesRatherThanAppends() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        try await handle.writeText("first version", to: .summaryMarkdown)
        try await handle.writeText("second version", to: .summaryMarkdown)

        #expect(try await handle.readText(.summaryMarkdown) == "second version")
    }

    @Test("writeJSON/writeText for an invalid watcher id throws rather than writing a file")
    func writeWithInvalidWatcherIdThrows() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        await #expect(throws: SessionFileError.self) {
            try await handle.writeText("x", to: .watcherDefinition(id: "../../etc/passwd"))
        }
        // No file should have escaped the session directory or the watchers/ subdirectory.
        let watchersDir = root.appendingPathComponent("watchers")
        let entries = (try? FileManager.default.contentsOfDirectory(atPath: watchersDir.path)) ?? []
        #expect(entries.isEmpty)
    }

    // MARK: - readEnabledWatchers / writeEnabledWatchers

    @Test("readEnabledWatchers returns an empty array when enabled.yaml does not exist")
    func readEnabledWatchersReturnsEmptyWhenMissing() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        #expect(try await handle.readEnabledWatchers() == [])
    }

    @Test("writeEnabledWatchers then readEnabledWatchers round-trips the exact list and order")
    func writeThenReadEnabledWatchersRoundTrips() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        let ids = ["pre-check", "action-items", "risk-check"]
        try await handle.writeEnabledWatchers(ids)

        #expect(try await handle.readEnabledWatchers() == ids)
        let yamlURL = root.appendingPathComponent("watchers/enabled.yaml")
        #expect(FileManager.default.fileExists(atPath: yamlURL.path))
        let raw = try String(contentsOf: yamlURL, encoding: .utf8)
        #expect(raw.contains("enabled"))
    }

    @Test("writeEnabledWatchers with an empty list round-trips to an empty array")
    func writeEnabledWatchersEmptyListRoundTrips() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        try await handle.writeEnabledWatchers([])
        #expect(try await handle.readEnabledWatchers() == [])
    }

    @Test("writeEnabledWatchers overwrites rather than appends")
    func writeEnabledWatchersOverwritesRatherThanAppends() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        try await handle.writeEnabledWatchers(["pre-check"])
        try await handle.writeEnabledWatchers(["action-items"])

        #expect(try await handle.readEnabledWatchers() == ["action-items"])
    }

    // MARK: - listSessionLocalWatcherIds

    @Test("listSessionLocalWatcherIds returns an empty array when the watchers directory does not exist")
    func listSessionLocalWatcherIdsReturnsEmptyWhenDirectoryMissing() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        #expect(try await handle.listSessionLocalWatcherIds() == [])
    }

    @Test("listSessionLocalWatcherIds lists .md definition files, sorted, excluding enabled.yaml and .state.json")
    func listSessionLocalWatcherIdsExcludesEnabledYamlAndStateFiles() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        try await handle.writeText("watcher b", to: .watcherDefinition(id: "watcher-b"))
        try await handle.writeText("watcher a", to: .watcherDefinition(id: "watcher-a"))
        try await handle.writeJSON(SampleState(count: 0, label: "state-only"), to: .watcherState(id: "watcher-a"))
        try await handle.writeEnabledWatchers(["watcher-a", "watcher-b"])

        let ids = try await handle.listSessionLocalWatcherIds()
        #expect(ids == ["watcher-a", "watcher-b"])
    }

    @Test("listSessionLocalWatcherIds does not list a watcher that only has a .state.json (no .md definition)")
    func listSessionLocalWatcherIdsOnlyCountsDefinitionFiles() async throws {
        let root = makeSessionDirectory()
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = makeHandle(directoryURL: root)

        try await handle.writeJSON(SampleState(count: 0, label: "state-only"), to: .watcherState(id: "preset-only"))

        #expect(try await handle.listSessionLocalWatcherIds() == [])
    }
}
