    @Test("appendTranscriptSegment persists sttSource to transcript.jsonl as the stt_source key, round-tripping on read")
    func appendTranscriptSegmentPersistsSttSourceToDisk() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let appended = try await handle.appendTranscriptSegment(
            source: .mic,
            startMs: 0,
            endMs: 500,
            text: "one",
            confidence: 0.9,
            sttSource: "batch"
        )

        let fileURL = directory.appendingPathComponent("transcript.jsonl")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        let object = try #require(JSONSerialization.jsonObject(with: Data(content.utf8)) as? [String: Any])
        #expect(object["stt_source"] as? String == "batch")

        let read = try await handle.readTranscriptSegments()
        #expect(read == [appended])
        #expect(read.first?.sttSource == "batch")
    }

    @Test("appendTranscriptSegment omits the stt_source key entirely on disk when sttSource is nil (MT9 byte-for-byte compatibility)")
    func appendTranscriptSegmentOmitsSttSourceKeyOnDiskWhenNil() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "one", confidence: 0.9)

        let fileURL = directory.appendingPathComponent("transcript.jsonl")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        let object = try #require(JSONSerialization.jsonObject(with: Data(content.utf8)) as? [String: Any])
        #expect(object["stt_source"] == nil)
        #expect(object.keys.contains("stt_source") == false)
    }

    @Test("appendTranscriptSegment supports a mix of batch-sourced and fallback (nil sttSource) segments in the same session")
    func appendTranscriptSegmentSupportsMixedSttSourceSegments() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let batchSourced = try await handle.appendTranscriptSegment(
            source: .mic,
            startMs: 0,
            endMs: 500,
            text: "one",
            confidence: 0.9,
            sttSource: "batch"
        )
        let fallback = try await handle.appendTranscriptSegment(source: .mic, startMs: 500, endMs: 1_000, text: "two", confidence: 0.9)

        let read = try await handle.readTranscriptSegments()
        #expect(read == [batchSourced, fallback])
        #expect(read[0].sttSource == "batch")
        #expect(read[1].sttSource == nil)
    }

