import Foundation
import Testing

@testable import Kikimi

/// Unit tests for `SessionHandle+Transcript.swift` (`docs/design/07-session-store.md` section 5.2/6/7;
/// kikimi.md 5 章/6 章). Mirrors `SessionHandleTests.swift`'s pattern of constructing `SessionHandle`
/// directly (`SessionHandle(directoryURL:meta:)`) rather than going through `SessionStore`, since
/// these tests only exercise this extension's own surface
/// (`appendTranscriptSegment`/`appendRefinedSegment`/`readTranscriptSegments`/`readRefinedSegments`).
///
/// See design doc section 13's layer-1 bullets this file targets: sequential `seg_id` assignment,
/// `segmentCount`/`refinedCount` matching the actual line counts, and corrupt-trailing-line vs.
/// corrupt-non-trailing-line read tolerance.
@Suite("SessionHandle+Transcript")
struct SessionHandleTranscriptTests {
    private func makeTempSessionDirectory() -> URL {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("SessionHandleTranscriptTests-\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    private func baseMeta(id: String = "2026-07-01T14-30-00_a1b2c3d4", segmentCount: Int = 0, refinedCount: Int = 0) -> SessionMeta {
        SessionMeta(
            id: id,
            title: "Test Session",
            titleAutoGenerated: true,
            titleAutoNamedOnce: false,
            titleProposal: nil,
            state: .recording,
            createdAt: Date(timeIntervalSince1970: 1_751_000_000),
            startedAt: Date(timeIntervalSince1970: 1_751_000_010),
            endedAt: nil,
            durationMs: 0,
            basedOnSession: nil,
            segmentCount: segmentCount,
            refinedCount: refinedCount,
            appVersion: "0.1.0"
        )
    }

    private func makeRefinedSegment(
        id: String,
        startMs: Int = 0,
        endMs: Int = 1_000,
        refinedText: String? = "refined text",
        error: String? = nil,
        batchId: String = "batch_00001"
    ) -> RefinedSegment {
        RefinedSegment(
            id: id,
            startMs: startMs,
            endMs: endMs,
            speaker: .mic,
            rawText: "raw text",
            refinedText: refinedText,
            error: error,
            refinedAt: Date(timeIntervalSince1970: 1_751_000_020),
            model: "claude-haiku-4-5-20251001",
            batchId: batchId
        )
    }

    // MARK: - appendTranscriptSegment: id assignment

    @Test("appendTranscriptSegment assigns sequential seg_ + 5-digit zero-padded ids in call order")
    func appendTranscriptSegmentAssignsSequentialIds() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let first = try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "one", confidence: 0.9)
        let second = try await handle.appendTranscriptSegment(source: .system, startMs: 500, endMs: 1_000, text: "two", confidence: 0.8)
        let third = try await handle.appendTranscriptSegment(source: .mic, startMs: 1_000, endMs: 1_500, text: "three", confidence: 0.95)

        #expect(first.id == "seg_00001")
        #expect(second.id == "seg_00002")
        #expect(third.id == "seg_00003")
    }

    @Test("appendTranscriptSegment continues the sequence from an already-nonzero segmentCount")
    func appendTranscriptSegmentContinuesFromExistingCount() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta(segmentCount: 41))

        let segment = try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "resumed", confidence: 0.9)

        #expect(segment.id == "seg_00042")
    }

    // MARK: - appendTranscriptSegment: meta.segmentCount / file content

    @Test("appendTranscriptSegment increments meta.segmentCount by exactly one per call")
    func appendTranscriptSegmentIncrementsSegmentCount() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "one", confidence: 0.9)
        try await handle.appendTranscriptSegment(source: .mic, startMs: 500, endMs: 1_000, text: "two", confidence: 0.9)

        #expect(await handle.meta.segmentCount == 2)
    }

    @Test("appendTranscriptSegment writes exactly one JSON line per call to transcript.jsonl")
    func appendTranscriptSegmentWritesOneLinePerCall() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "one", confidence: 0.9)
        try await handle.appendTranscriptSegment(source: .system, startMs: 500, endMs: 1_000, text: "two", confidence: 0.8)

        let fileURL = directory.appendingPathComponent("transcript.jsonl")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        let lines = content.split(separator: "\n", omittingEmptySubsequences: true)
        #expect(lines.count == 2)
    }

