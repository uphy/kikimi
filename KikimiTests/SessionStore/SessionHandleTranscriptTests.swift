    // MARK: - readTranscriptSegments: corrupt-line tolerance (design doc section 7/12)

    @Test("readTranscriptSegments skips a corrupt trailing line and still returns the valid ones (mid-write crash)")
    func readTranscriptSegmentsSkipsCorruptTrailingLine() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let first = try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "one", confidence: 0.9)
        let second = try await handle.appendTranscriptSegment(source: .mic, startMs: 500, endMs: 1_000, text: "two", confidence: 0.9)

        // Simulate a crash mid-write: append a truncated, invalid trailing line directly to disk.
        let fileURL = directory.appendingPathComponent("transcript.jsonl")
        let handleForCorruption = try #require(FileHandle(forWritingAtPath: fileURL.path))
        try handleForCorruption.seekToEnd()
        try handleForCorruption.write(contentsOf: Data("{\"id\": \"seg_00003\", \"start_ms\": tr".utf8))
        try handleForCorruption.close()

        let read = try await handle.readTranscriptSegments()
        #expect(read == [first, second])
    }

    @Test("readTranscriptSegments skips a corrupt non-trailing line but still returns valid lines before and after it")
    func readTranscriptSegmentsSkipsCorruptNonTrailingLine() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }

        let encoder = SessionJSONCoding.makeEncoder()
        let validFirst = TranscriptSegment(id: "seg_00001", startMs: 0, endMs: 500, speaker: .mic, text: "one", confidence: 0.9)
        let validThird = TranscriptSegment(id: "seg_00003", startMs: 1_000, endMs: 1_500, speaker: .mic, text: "three", confidence: 0.9)

        var fileContent = ""
        fileContent += String(data: try encoder.encode(validFirst), encoding: .utf8)! + "\n"
        fileContent += "{this is not valid json at all}\n"
        fileContent += String(data: try encoder.encode(validThird), encoding: .utf8)! + "\n"

        let fileURL = directory.appendingPathComponent("transcript.jsonl")
        try fileContent.write(to: fileURL, atomically: true, encoding: .utf8)

        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())
        let read = try await handle.readTranscriptSegments()

        #expect(read == [validFirst, validThird])
    }

    // MARK: - Re-opening: "open once, seek once" append continuity

    @Test("appending against pre-existing transcript.jsonl content (from a previous run) appends after it instead of overwriting it")
    func appendPreservesPreExistingFileContent() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }

        // Simulate content already on disk from a previous run, written *before* any `SessionHandle`
        // for this directory has ever touched `transcript.jsonl` — so the append-only writer this
        // extension caches per file path (`AppendOnlyLogFileRegistry`) has no entry for this path
        // yet, and its first `appendTranscriptSegment` call below must open the file fresh and seek
        // to its existing end, exactly like a real app relaunch discovering a session's existing log
        // (design doc section 7, "開いたら追記のみ、seekしない" applied once at open time).
        let existing = TranscriptSegment(id: "seg_00001", startMs: 0, endMs: 500, speaker: .mic, text: "existing", confidence: 0.9)
        let encoder = SessionJSONCoding.makeEncoder()
        let existingLine = String(data: try encoder.encode(existing), encoding: .utf8)! + "\n"
        try existingLine.write(to: directory.appendingPathComponent("transcript.jsonl"), atomically: true, encoding: .utf8)

        let handle = SessionHandle(directoryURL: directory, meta: baseMeta(segmentCount: 1))
        let appended = try await handle.appendTranscriptSegment(source: .mic, startMs: 500, endMs: 1_000, text: "new", confidence: 0.9)

        let read = try await handle.readTranscriptSegments()
        #expect(read == [existing, appended])
    }

    // MARK: - ensureTranscriptAndRefinedLogFilesExist (design doc section 7: "SessionHandle が
    // セッションを開いた時点で FileHandle を1つ開きっぱなしにし")

    @Test("ensureTranscriptAndRefinedLogFilesExist creates empty transcript.jsonl/refined.jsonl when neither exists yet")
    func ensureTranscriptAndRefinedLogFilesExistCreatesMissingFiles() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let transcriptURL = directory.appendingPathComponent("transcript.jsonl")
        let refinedURL = directory.appendingPathComponent("refined.jsonl")
        #expect(!FileManager.default.fileExists(atPath: transcriptURL.path))
        #expect(!FileManager.default.fileExists(atPath: refinedURL.path))

        try await handle.ensureTranscriptAndRefinedLogFilesExist()

        #expect(FileManager.default.fileExists(atPath: transcriptURL.path))
        #expect(FileManager.default.fileExists(atPath: refinedURL.path))
        #expect(try await handle.readTranscriptSegments().isEmpty)
        #expect(try await handle.readRefinedSegments().isEmpty)
    }

    @Test("ensureTranscriptAndRefinedLogFilesExist does not truncate pre-existing transcript.jsonl/refined.jsonl content")
    func ensureTranscriptAndRefinedLogFilesExistPreservesExistingContent() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }

        let existingTranscript = TranscriptSegment(id: "seg_00001", startMs: 0, endMs: 500, speaker: .mic, text: "existing", confidence: 0.9)
        let encoder = SessionJSONCoding.makeEncoder()
        let existingTranscriptLine = String(data: try encoder.encode(existingTranscript), encoding: .utf8)! + "\n"
        try existingTranscriptLine.write(to: directory.appendingPathComponent("transcript.jsonl"), atomically: true, encoding: .utf8)

        let handle = SessionHandle(directoryURL: directory, meta: baseMeta(segmentCount: 1))
        try await handle.ensureTranscriptAndRefinedLogFilesExist()

        #expect(try await handle.readTranscriptSegments() == [existingTranscript])

        // Appending afterward must continue after the pre-existing content, not overwrite it — the same
        // "open once, seek once" continuity `appendPreservesPreExistingFileContent` verifies without this
        // extra `ensureTranscriptAndRefinedLogFilesExist()` call.
        let appended = try await handle.appendTranscriptSegment(source: .mic, startMs: 500, endMs: 1_000, text: "new", confidence: 0.9)
        #expect(try await handle.readTranscriptSegments() == [existingTranscript, appended])
    }

    @Test("ensureTranscriptAndRefinedLogFilesExist is idempotent across repeated calls")
    func ensureTranscriptAndRefinedLogFilesExistIsIdempotent() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.ensureTranscriptAndRefinedLogFilesExist()
        let appended = try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "one", confidence: 0.9)
        try await handle.ensureTranscriptAndRefinedLogFilesExist()

        #expect(try await handle.readTranscriptSegments() == [appended])
    }

    // MARK: - closeAppendOnlyLogFiles (SessionStore.deleteSession(_:) FileHandle cleanup)

    @Test("closeAppendOnlyLogFiles evicts the cached FileHandle so a path reused after deletion starts from a fresh file, not the old open handle")
    func closeAppendOnlyLogFilesEvictsCachedHandle() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }

        // Simulate a session that was opened and written to (as `SessionStore.deleteSession(_:)`
        // would find one keyed in `AppendOnlyLogFileRegistry` by this exact path).
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())
        _ = try await handle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "before delete", confidence: 0.9)

        // `SessionStore.deleteSession(_:)` calls this before removing the directory.
        SessionHandle.closeAppendOnlyLogFiles(inSessionDirectory: directory)
        try FileManager.default.removeItem(at: directory)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)

        // Without evicting the cache, `AppendOnlyLogFileRegistry` (keyed by this same absolute path)
        // would hand back the stale `FileHandle` left pointing at the now-unlinked inode, so this
        // append would silently vanish instead of landing in the freshly recreated file.
        let freshHandle = SessionHandle(directoryURL: directory, meta: baseMeta())
        let appended = try await freshHandle.appendTranscriptSegment(source: .mic, startMs: 0, endMs: 500, text: "after delete", confidence: 0.9)

        #expect(try await freshHandle.readTranscriptSegments() == [appended])
    }

    @Test("closeAppendOnlyLogFiles is a no-op for a directory whose log files were never opened")
    func closeAppendOnlyLogFilesIsNoOpWhenNeverOpened() {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }

        SessionHandle.closeAppendOnlyLogFiles(inSessionDirectory: directory)
    }
