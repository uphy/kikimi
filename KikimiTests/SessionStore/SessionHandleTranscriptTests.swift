    func appendTranscriptSegmentThreadsExplicitSttSource() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let segment = try await handle.appendTranscriptSegment(
