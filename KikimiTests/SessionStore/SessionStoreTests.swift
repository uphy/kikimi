          "segment_count": 342,
          "refined_count": 342,
          "app_version": "0.1.0"
        }
        """
        let meta = try SessionJSONCoding.makeDecoder().decode(SessionMeta.self, from: Data(sample.utf8))

        #expect(meta.id == "2026-07-01T14-30-00_a1b2c3d4")
        #expect(meta.title == "デイリースクラム")
        #expect(meta.titleAutoGenerated)
        #expect(meta.titleAutoNamedOnce)
        #expect(meta.titleProposal == nil)
        #expect(meta.state == .ended)
        #expect(meta.durationMs == 2_722_000)
        #expect(meta.basedOnSession == "2026-06-24T14-30-00_x9y8z7w6")
        #expect(meta.segmentCount == 342)
        #expect(meta.refinedCount == 342)
        #expect(meta.appVersion == "0.1.0")

        let expectedFormatter = ISO8601DateFormatter()
        #expect(meta.createdAt == expectedFormatter.date(from: "2026-07-01T14:28:12Z"))
        #expect(meta.startedAt == expectedFormatter.date(from: "2026-07-01T14:30:00Z"))
        #expect(meta.endedAt == expectedFormatter.date(from: "2026-07-01T15:15:22Z"))
    }

    @Test("SessionMeta round-trips through SessionJSONCoding's encoder/decoder with snake_case keys and ISO 8601 date strings")
    func sessionMetaRoundTripsThroughSessionJSONCoding() throws {
        let meta = SessionMeta(
            id: "2026-07-01T14-30-00_a1b2c3d4",
            title: "デイリースクラム",
            titleAutoGenerated: true,
            titleAutoNamedOnce: false,
            titleProposal: nil,
            state: .draft,
            createdAt: Date(timeIntervalSince1970: 1_782_916_092), // 2026-07-01T14:28:12Z
            startedAt: nil,
            endedAt: nil,
            durationMs: 0,
            basedOnSession: nil,
            segmentCount: 0,
            refinedCount: 0,
            appVersion: "0.1.0"
        )

        let data = try SessionJSONCoding.makeEncoder().encode(meta)
        let jsonObject = try #require(JSONSerialization.jsonObject(with: data) as? [String: Any])

        // Field names on disk must be snake_case, not the Swift camelCase property names.
        #expect(jsonObject["title_auto_generated"] as? Bool == true)
        #expect(jsonObject["title_auto_named_once"] as? Bool == false)
        #expect(jsonObject["segment_count"] as? Int == 0)

        // Dates must be ISO 8601 strings, not Foundation's default epoch-seconds encoding.
        let createdAtString = try #require(jsonObject["created_at"] as? String)
        #expect(createdAtString == "2026-07-01T14:28:12Z")

        let decoded = try SessionJSONCoding.makeDecoder().decode(SessionMeta.self, from: data)
        #expect(decoded == meta)
    }

    @Test("TranscriptSegment/RefinedSegment round-trip kikimi.md's sample line shapes")
    func transcriptAndRefinedSegmentRoundTrip() throws {
        let transcriptSample = """
        {"id": "seg_00042", "start_ms": 125300, "end_ms": 128100, "speaker": "mic", "text": "そうですね、次のスプリントで対応します", "confidence": 0.87}
        """
        let segment = try SessionJSONCoding.makeDecoder().decode(TranscriptSegment.self, from: Data(transcriptSample.utf8))
        #expect(segment.id == "seg_00042")
        #expect(segment.startMs == 125_300)
        #expect(segment.endMs == 128_100)
        #expect(segment.speaker == .mic)
        #expect(segment.confidence == 0.87)

        let refined = RefinedSegment(
            id: segment.id,
            startMs: segment.startMs,
            endMs: segment.endMs,
            speaker: segment.speaker,
            rawText: segment.text,
            refinedText: "次のスプリントで対応します。",
            error: nil,
            refinedAt: Date(timeIntervalSince1970: 1_782_916_335), // 2026-07-01T14:32:15Z
            model: "claude-haiku-4-5-20251001",
            batchId: "batch_00004"
        )
        let encoded = try SessionJSONCoding.makeEncoder().encode(refined)
        // transcript.jsonl/refined.jsonl lines must never contain an embedded newline.
        #expect(!String(data: encoded, encoding: .utf8)!.contains("\n"))
        let decoded = try SessionJSONCoding.makeDecoder().decode(RefinedSegment.self, from: encoded)
        #expect(decoded == refined)
    }

