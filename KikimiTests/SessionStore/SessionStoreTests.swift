    // MARK: - meta.json read-modify-write / flush throttling (section 7)

    @Test("updateMeta is idempotent: applying the same mutation twice yields the same persisted meta.json")
    func updateMetaIsIdempotent() async throws {
        let (store, root) = makeStore()
        defer { try? FileManager.default.removeItem(at: root) }

        let meta = try await store.createDraftSession()
        let handle = try await store.openSession(meta.id)

        try await handle.updateMeta { $0.title = "Standup" }
        let firstResult = await handle.meta
        try await handle.updateMeta { $0.title = "Standup" }
        let secondResult = await handle.meta
        #expect(firstResult == secondResult)

        // Compare against a JSON-round-tripped `secondResult` rather than the raw in-memory value:
        // `SessionJSONCoding`'s `.iso8601` date strategy (no fractional seconds, matching kikimi.md 5 章's
        // sample `"created_at": "2026-07-01T14:28:12Z"`) necessarily drops `createdAt`'s sub-second
        // precision once it round-trips through disk, so comparing the on-disk value directly against the
        // full-precision in-memory `Date()` would fail even though persistence is behaving correctly.
        let directory = sessionDirectory(root: root, sessionId: meta.id)
        let onDisk = try SessionJSONCoding.makeDecoder().decode(SessionMeta.self, from: Data(contentsOf: directory.appendingPathComponent("meta.json")))
        let secondResultRoundTripped = try SessionJSONCoding.makeDecoder().decode(
            SessionMeta.self,
            from: SessionJSONCoding.makeEncoder().encode(secondResult)
        )
        #expect(onDisk == secondResultRoundTripped)
    }

