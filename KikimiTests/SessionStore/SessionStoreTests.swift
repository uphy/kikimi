    @Test("SessionStore.shared's AppConfig.data.defaults wiring pattern copies default context/template content into a new Draft session (docs/design/26-settings-ui.md §4.2)")
    func createDraftSessionUsesAppConfigDrivenDefaults() async throws {
        let root = makeTemporaryDirectory()
        defer { try? FileManager.default.removeItem(at: root) }

        // A standalone AppConfig (not AppConfig.shared) pointed at absolute paths under `root`, so
        // this never touches the real ~/.config/kikimi -- same DI convention as AppConfigTests.
        let configDirectory = root.appendingPathComponent("config", isDirectory: true)
        let contextURL = root.appendingPathComponent("custom-context.md")
        let templateURL = root.appendingPathComponent("custom-template.md")
        try "# 事前メモ\n次回定例のアジェンダ".write(to: contextURL, atomically: true, encoding: .utf8)
        try "# {{title}}\nカスタムテンプレート".write(to: templateURL, atomically: true, encoding: .utf8)

        let appConfig = AppConfig(directory: configDirectory, credentialStore: InMemoryCredentialStore())
        appConfig.update { config in
            config.defaults = DefaultsConfig(contextFile: contextURL.path, summaryTemplateFile: templateURL.path)
        }

        // Mirrors `SessionStore.shared`'s own construction line exactly: `FileManager.
        // expandingTildePath(AppConfig...data.defaults.xxx)` feeding `SessionStore.init(...)`.
        let store = SessionStore(
            sessionsRootDirectory: root.appendingPathComponent("sessions", isDirectory: true),
            defaultContextFileURL: FileManager.expandingTildePath(appConfig.data.defaults.contextFile),
            defaultSummaryTemplateFileURL: FileManager.expandingTildePath(appConfig.data.defaults.summaryTemplateFile)
        )

        let meta = try await store.createDraftSession()
        let handle = try await store.openSession(meta.id)
        #expect(await handle.readContext() == "# 事前メモ\n次回定例のアジェンダ")
        #expect(await handle.readSummaryTemplate() == "# {{title}}\nカスタムテンプレート")
    }

