    // MARK: - Recording segment lifecycle: begin -> pause -> resume -> pause -> end -> reopen
    // (kikimi.md 4 章 "「停止」と「終了」を分離する", 5/6 章 recordings[]/duration_ms/start_ms_offset)

    @Test("begin -> pause -> resume -> pause -> end builds recordings[] with correct index/startMsOffset, and durationMs accumulates only closed segments")
    func fullPauseResumeCycleBuildsCorrectRecordings() async throws {
        let (store, root) = makeStore()
        defer { try? FileManager.default.removeItem(at: root) }

        let created = try await store.createDraftSession()

        // Segment 0: Draft -> Recording.
        _ = try await store.beginRecording(created.id)
        var meta = try await store.openSession(created.id).meta
        #expect(meta.state == .recording)
        #expect(meta.recordings.count == 1)
        #expect(meta.recordings[0].index == 0)
        #expect(meta.recordings[0].startMsOffset == 0)
        #expect(meta.recordings[0].endedAt == nil)
        #expect(meta.durationMs == 0)

        // Segment 0 closes: Recording -> Paused. Pausing releases the recording-exclusivity flag
        // (kikimi.md 4 章: "他ウィンドウのため音声リソースが解放される").
        try await store.pauseRecording(created.id)
        #expect(await store.recordingSessionId == nil)
        meta = try await store.openSession(created.id).meta
        #expect(meta.state == .paused)
        #expect(meta.recordings.count == 1)
        #expect(meta.recordings[0].endedAt != nil)
        let firstSegmentDurationMs = meta.durationMs
        #expect(firstSegmentDurationMs >= 0)

        // Segment 1 opens: Paused -> Recording, offset by the first segment's length.
        _ = try await store.resumeRecording(created.id)
        #expect(await store.recordingSessionId == created.id)
        meta = try await store.openSession(created.id).meta
        #expect(meta.state == .recording)
        #expect(meta.recordings.count == 2)
        #expect(meta.recordings[1].index == 1)
        #expect(meta.recordings[1].startMsOffset == firstSegmentDurationMs)
        #expect(meta.recordings[1].endedAt == nil)
        // durationMs still reflects only the first (closed) segment while the second is open.
        #expect(meta.durationMs == firstSegmentDurationMs)

        // Segment 1 closes: Recording -> Paused again.
        try await store.pauseRecording(created.id)
        meta = try await store.openSession(created.id).meta
        #expect(meta.state == .paused)
        #expect(meta.recordings.count == 2)
        #expect(meta.recordings[1].endedAt != nil)
        #expect(meta.durationMs >= firstSegmentDurationMs)

        // Paused -> Ended: the sole confirmation operation. No new segment opens; endedAt is set.
        try await store.endMeeting(created.id)
        meta = try await store.openSession(created.id).meta
        #expect(meta.state == .ended)
        #expect(meta.recordings.count == 2)
        #expect(meta.endedAt != nil)
        let durationMsAtEnd = meta.durationMs

        // Ended -> Recording (救済パス): opens a third segment and clears endedAt.
        _ = try await store.reopenForRecording(created.id)
        #expect(await store.recordingSessionId == created.id)
        meta = try await store.openSession(created.id).meta
        #expect(meta.state == .recording)
        #expect(meta.endedAt == nil)
        #expect(meta.recordings.count == 3)
        #expect(meta.recordings[2].index == 2)
        #expect(meta.recordings[2].startMsOffset == durationMsAtEnd)
    }

