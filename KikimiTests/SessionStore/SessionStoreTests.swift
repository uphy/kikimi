    @Test("SessionMeta decodes kikimi.md's sample meta.json with snake_case keys and ISO 8601 dates")
    func sessionMetaDecodesKikimiSample() throws {
        let sample = """
        {
          "id": "2026-07-01T14-30-00_a1b2c3d4",
          "title": "デイリースクラム",
          "title_auto_generated": true,
          "title_auto_named_once": true,
          "title_proposal": null,
          "state": "ended",
          "created_at": "2026-07-01T14:28:12Z",
          "started_at": "2026-07-01T14:30:00Z",
