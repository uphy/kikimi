import Foundation
import Testing

@testable import Kikimi

/// Unit tests for `SessionHandle+Diarization.swift` (`docs/design/13-speaker-diarization.md`
/// section 4.1-4.3). Mirrors `SessionHandleTranscriptTests.swift`'s pattern of constructing
/// `SessionHandle` directly (`SessionHandle(directoryURL:meta:)`) rather than going through
/// `SessionStore`, since these tests only exercise this extension's own surface
/// (`appendDiarizationTurn`/`readDiarizationTurns`/`readSpeakerAssignments`/
/// `updateSpeakerAssignments`).
///
/// See design doc section 11's layer-1 bullets this file targets: `diarization.jsonl`/
/// `speaker_assignments.json` snake_case round-trip, append accumulation/ordering, corrupt-trailing-
/// line tolerance, and `updateSpeakerAssignments`'s mutate-closure semantics.
@Suite("SessionHandle+Diarization")
struct SessionHandleDiarizationTests {
    private func makeTempSessionDirectory() -> URL {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("SessionHandleDiarizationTests-\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    private func baseMeta(id: String = "2026-07-01T14-30-00_a1b2c3d4") -> SessionMeta {
        SessionMeta(
            id: id,
            title: "Test Session",
            titleAutoGenerated: true,
            titleAutoNamedOnce: false,
            titleProposal: nil,
            state: .recording,
            createdAt: Date(timeIntervalSince1970: 1_751_000_000),
            startedAt: Date(timeIntervalSince1970: 1_751_000_010),
            endedAt: nil,
            durationMs: 0,
            basedOnSession: nil,
            segmentCount: 0,
            refinedCount: 0,
            appVersion: "0.1.0"
        )
    }

    // MARK: - appendDiarizationTurn / readDiarizationTurns: snake_case round-trip

    @Test("readDiarizationTurns round-trips every appended turn with snake_case slot/start_ms/end_ms fields")
    func appendAndReadRoundTrips() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let first = DiarizationTurn(slot: "spk_1", startMs: 0, endMs: 12_300)
        let second = DiarizationTurn(slot: "spk_2", startMs: 11_800, endMs: 15_400)
        try await handle.appendDiarizationTurn(first)
        try await handle.appendDiarizationTurn(second)

        let fileURL = directory.appendingPathComponent("diarization.jsonl")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        #expect(content.contains("\"slot\""))
        #expect(content.contains("\"start_ms\""))
        #expect(content.contains("\"end_ms\""))
        #expect(!content.contains("startMs"))
        #expect(!content.contains("endMs"))

        let read = try await handle.readDiarizationTurns()
        #expect(read == [first, second])
    }

    @Test("appendDiarizationTurn accumulates turns in append order, one JSON line per call")
    func appendAccumulatesInOrder() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let turns = [
            DiarizationTurn(slot: "spk_1", startMs: 0, endMs: 1_000),
            DiarizationTurn(slot: "spk_1", startMs: 1_500, endMs: 2_500),
            DiarizationTurn(slot: "spk_2", startMs: 2_000, endMs: 3_000)
        ]
        for turn in turns {
            try await handle.appendDiarizationTurn(turn)
        }

        let fileURL = directory.appendingPathComponent("diarization.jsonl")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        let lines = content.split(separator: "\n", omittingEmptySubsequences: true)
        #expect(lines.count == 3)

        let read = try await handle.readDiarizationTurns()
        #expect(read == turns)
    }

    // MARK: - readDiarizationTurns: missing file / empty session

    @Test("readDiarizationTurns returns an empty array for a session that has never appended a turn")
    func readReturnsEmptyWhenNeverWritten() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        #expect(try await handle.readDiarizationTurns().isEmpty)
    }

    // MARK: - readDiarizationTurns: corrupt trailing line tolerance

    @Test("readDiarizationTurns skips a corrupt trailing line and still returns the valid ones (mid-write crash)")
    func readSkipsCorruptTrailingLine() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let first = DiarizationTurn(slot: "spk_1", startMs: 0, endMs: 1_000)
        let second = DiarizationTurn(slot: "spk_2", startMs: 500, endMs: 1_500)
        try await handle.appendDiarizationTurn(first)
        try await handle.appendDiarizationTurn(second)

        // Simulate a crash mid-write: append a truncated, invalid trailing line directly to disk.
        let fileURL = directory.appendingPathComponent("diarization.jsonl")
        let corruptionHandle = try #require(FileHandle(forWritingAtPath: fileURL.path))
        try corruptionHandle.seekToEnd()
        try corruptionHandle.write(contentsOf: Data("{\"slot\": \"spk_3\", \"start_ms\": tr".utf8))
        try corruptionHandle.close()

        let read = try await handle.readDiarizationTurns()
        #expect(read == [first, second])
    }

    @Test("readDiarizationTurns skips a corrupt non-trailing line but still returns valid lines before and after it")
    func readSkipsCorruptNonTrailingLine() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }

        let encoder = SessionJSONCoding.makeEncoder()
        let validFirst = DiarizationTurn(slot: "spk_1", startMs: 0, endMs: 1_000)
        let validThird = DiarizationTurn(slot: "spk_2", startMs: 2_000, endMs: 3_000)

        var fileContent = ""
        fileContent += String(data: try encoder.encode(validFirst), encoding: .utf8)! + "\n"
        fileContent += "{this is not valid json at all}\n"
        fileContent += String(data: try encoder.encode(validThird), encoding: .utf8)! + "\n"

        let fileURL = directory.appendingPathComponent("diarization.jsonl")
        try fileContent.write(to: fileURL, atomically: true, encoding: .utf8)

        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())
        let read = try await handle.readDiarizationTurns()

        #expect(read == [validFirst, validThird])
    }

    // MARK: - readSpeakerAssignments: snake_case round-trip / missing file

    @Test("readSpeakerAssignments returns an empty SpeakerAssignments for a session that has never written one")
    func readSpeakerAssignmentsReturnsEmptyWhenMissing() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let assignments = try await handle.readSpeakerAssignments()
        #expect(assignments == SpeakerAssignments())
        #expect(assignments.assignments.isEmpty)
    }

    @Test("updateSpeakerAssignments then readSpeakerAssignments round-trips assignments, keyed by slot, with snake_case fields")
    func updateThenReadRoundTrips() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.updateSpeakerAssignments { assignments in
            assignments.assignments["spk_1"] = SlotAssignment(
                globalSpeakerId: "b3f1",
                displayName: "田中さん",
                assignedBy: .auto,
                embedding: [0.012, -0.34]
            )
            assignments.assignments["spk_2"] = SlotAssignment()
        }

        let fileURL = directory.appendingPathComponent("speaker_assignments.json")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        #expect(content.contains("\"assignments\""))
        #expect(content.contains("\"global_speaker_id\""))
        #expect(content.contains("\"display_name\""))
        #expect(content.contains("\"assigned_by\""))
        #expect(content.contains("\"embedding\""))

        let read = try await handle.readSpeakerAssignments()
        #expect(read.assignments["spk_1"]?.displayName == "田中さん")
        #expect(read.assignments["spk_1"]?.globalSpeakerId == "b3f1")
        #expect(read.assignments["spk_1"]?.assignedBy == .auto)
        #expect(read.assignments["spk_1"]?.embedding == [0.012, -0.34])
        #expect(read.assignments["spk_2"] == SlotAssignment())
    }

    // MARK: - updateSpeakerAssignments: mutate reflects incremental edits, including on an existing file

    @Test("updateSpeakerAssignments applies each mutate call on top of the previous write, not from a stale in-memory copy")
    func updateSpeakerAssignmentsAppliesIncrementalMutations() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.updateSpeakerAssignments { assignments in
            assignments.assignments["spk_1"] = SlotAssignment(displayName: nil, assignedBy: nil)
        }
        try await handle.updateSpeakerAssignments { assignments in
            assignments.assignments["spk_1"]?.displayName = "Speaker 1"
            assignments.assignments["spk_1"]?.assignedBy = .auto
        }
        try await handle.updateSpeakerAssignments { assignments in
            // A user rename must not be clobbered by re-reading a stale snapshot: this mutate sees
            // the auto assignment from the previous call and overwrites it with a user one.
            assignments.assignments["spk_1"]?.displayName = "田中さん"
            assignments.assignments["spk_1"]?.assignedBy = .user
        }

        let read = try await handle.readSpeakerAssignments()
        #expect(read.assignments["spk_1"]?.displayName == "田中さん")
        #expect(read.assignments["spk_1"]?.assignedBy == .user)
    }

    @Test("updateSpeakerAssignments seeds mutate with an empty SpeakerAssignments when the file does not exist yet")
    func updateSpeakerAssignmentsInitializesFromMissingFile() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        var sawEmptyOnEntry = false
        try await handle.updateSpeakerAssignments { assignments in
            sawEmptyOnEntry = assignments.assignments.isEmpty
            assignments.assignments["spk_1"] = SlotAssignment(displayName: "Speaker 1")
        }

        #expect(sawEmptyOnEntry)
        let read = try await handle.readSpeakerAssignments()
        #expect(read.assignments["spk_1"]?.displayName == "Speaker 1")
    }

    // MARK: - segment overrides ("この発言だけ変更", design section 6.1)

    @Test("segment overrides round-trip alongside slot assignments, keyed by segment id")
    func segmentOverridesRoundTrip() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.updateSpeakerAssignments { assignments in
            assignments.assignments["spk_1"] = SlotAssignment(displayName: "田中さん", assignedBy: .user)
            assignments.segmentOverrides["seg_00042"] = SegmentSpeakerOverride(displayName: "佐藤さん")
        }
        try await handle.updateSpeakerAssignments { assignments in
            assignments.segmentOverrides.removeValue(forKey: "seg_99999")  // no-op removal is safe
        }

        let read = try await handle.readSpeakerAssignments()
        #expect(read.assignments["spk_1"]?.displayName == "田中さん")
        #expect(read.segmentOverrides == ["seg_00042": SegmentSpeakerOverride(displayName: "佐藤さん")])
    }

    @Test("a speaker_assignments.json written before segment_overrides existed decodes as no overrides, not an error")
    func speakerAssignmentsWithoutOverridesKeyStillDecodes() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        // The exact on-disk shape R1's first build wrote: an assignments map and nothing else.
        let legacyJSON = """
        {"assignments":{"spk_1":{"global_speaker_id":null,"display_name":"田中さん","assigned_by":"user","embedding":null}}}
        """
        try legacyJSON.write(
            to: directory.appendingPathComponent("speaker_assignments.json"),
            atomically: true,
            encoding: .utf8
        )

        let read = try await handle.readSpeakerAssignments()
        #expect(read.assignments["spk_1"]?.displayName == "田中さん")
        #expect(read.segmentOverrides.isEmpty)
    }

    // MARK: - SegmentSpeakerOverride.globalSpeakerId round-trip
    // (`docs/design/20-voiceprint-misassignment-mitigation.md` section 5.1)

    @Test("a segment override's globalSpeakerId round-trips through speaker_assignments.json")
    func segmentOverrideGlobalSpeakerIdRoundTrips() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.updateSpeakerAssignments { assignments in
            assignments.segmentOverrides["seg_00042"] = SegmentSpeakerOverride(
                displayName: "佐藤さん",
                globalSpeakerId: "b3f1"
            )
        }

        let read = try await handle.readSpeakerAssignments()
        #expect(read.segmentOverrides["seg_00042"] == SegmentSpeakerOverride(displayName: "佐藤さん", globalSpeakerId: "b3f1"))

        // Also confirm the on-disk shape actually carries the snake_case key, not just that the
        // in-memory round-trip happens to agree.
        let onDiskText = try String(contentsOf: directory.appendingPathComponent("speaker_assignments.json"), encoding: .utf8)
        #expect(onDiskText.contains("\"global_speaker_id\":\"b3f1\""))
    }

    @Test("a segment override written before globalSpeakerId existed decodes with globalSpeakerId nil, not an error")
    func segmentOverrideWithoutGlobalSpeakerIdKeyStillDecodes() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        // The exact on-disk shape V2's predecessor wrote: a segment override with no
        // `global_speaker_id` key at all.
        let legacyJSON = """
        {"assignments":{},"segment_overrides":{"seg_00042":{"display_name":"佐藤さん"}}}
        """
        try legacyJSON.write(
            to: directory.appendingPathComponent("speaker_assignments.json"),
            atomically: true,
            encoding: .utf8
        )

        let read = try await handle.readSpeakerAssignments()
        #expect(read.segmentOverrides["seg_00042"] == SegmentSpeakerOverride(displayName: "佐藤さん", globalSpeakerId: nil))
    }

    // MARK: - participants.json (`docs/design/22-participant-hints.md` section 1.2)

    @Test("readParticipants returns an empty SessionParticipants for a session that has never written one")
    func readParticipantsReturnsEmptyWhenMissing() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        let participants = await handle.readParticipants()
        #expect(participants == SessionParticipants())
    }

    @Test("updateParticipants then readParticipants round-trips the roster with snake_case fields")
    func updateThenReadParticipantsRoundTrips() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.updateParticipants { participants in
            participants.addParticipant("b3f1")
            participants.addParticipant("c4a2")
        }

        let fileURL = directory.appendingPathComponent("participants.json")
        let content = try String(contentsOf: fileURL, encoding: .utf8)
        #expect(content.contains("\"participant_ids\""))
        #expect(content.contains("\"removed_participant_ids\""))

        let read = await handle.readParticipants()
        #expect(read.participantIds == ["b3f1", "c4a2"])
        #expect(read.removedParticipantIds.isEmpty)
    }

    @Test("updateParticipants applies each mutate call on top of the previous write, not from a stale in-memory copy")
    func updateParticipantsAppliesIncrementalMutations() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try await handle.updateParticipants { participants in
            participants.addParticipant("b3f1")
        }
        try await handle.updateParticipants { participants in
            participants.addParticipant("c4a2")
        }
        try await handle.updateParticipants { participants in
            participants.removeParticipant("b3f1")
        }

        let read = await handle.readParticipants()
        #expect(read.participantIds == ["c4a2"])
        #expect(read.removedParticipantIds == ["b3f1"])
    }

    @Test("updateParticipants seeds mutate with an empty SessionParticipants when the file does not exist yet")
    func updateParticipantsInitializesFromMissingFile() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        var sawEmptyOnEntry = false
        try await handle.updateParticipants { participants in
            sawEmptyOnEntry = participants.participantIds.isEmpty && participants.removedParticipantIds.isEmpty
            participants.addParticipant("b3f1")
        }

        #expect(sawEmptyOnEntry)
        let read = await handle.readParticipants()
        #expect(read.participantIds == ["b3f1"])
    }

    @Test("readParticipants falls back to an empty roster (not a throw) for a corrupt participants.json")
    func readParticipantsFallsBackOnCorruptFile() async throws {
        let directory = makeTempSessionDirectory()
        defer { try? FileManager.default.removeItem(at: directory) }
        let handle = SessionHandle(directoryURL: directory, meta: baseMeta())

        try Data("{ this is not valid json".utf8).write(to: directory.appendingPathComponent("participants.json"))

        let participants = await handle.readParticipants()
        #expect(participants == SessionParticipants())
    }
}
