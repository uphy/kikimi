import Foundation
import Testing

@testable import Kikimi

/// Unit coverage for the session-store pieces of Meet auto-record that the other suites do not hit
/// (`docs/design/50-meet-auto-record.md` §3.1 / §3.5): `markAbandonedRecordingPaused`, the no-op
/// branch of `abandonRecording`, `DraftMetaOverrides` resolution, and `AutoRecordMeta` coding.
@Suite("SessionStore abandon + auto-record meta (design 50)")
struct SessionStoreAbandonTests {
    private func makeStore() -> (store: SessionStore, root: URL) {
        let root = FileManager.default.temporaryDirectory
            .appendingPathComponent("SessionStoreAbandonTests-\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: root, withIntermediateDirectories: true)
        let store = SessionStore(
            sessionsRootDirectory: root.appendingPathComponent("sessions", isDirectory: true),
            defaultContextFileURL: root.appendingPathComponent("missing-context.md"),
            defaultSummaryTemplateFileURL: root.appendingPathComponent("missing-template.md"),
            defaultEnabledWatchersFileURL: root.appendingPathComponent("missing-enabled.yaml"),
            profilesDirectoryURL: root.appendingPathComponent("missing-profiles", isDirectory: true)
        )
        return (store, root)
    }

    @Test("abandonRecording is a no-op for a session that does not hold the flag")
    func abandonOtherSessionIsNoOp() async throws {
        let (store, root) = makeStore()
        defer { try? FileManager.default.removeItem(at: root) }
        let first = try await store.createDraftSession(seed: .none)
        _ = try await store.beginRecording(first.meta.id)

        await store.abandonRecording("some-other-session")

        #expect(await store.recordingSessionId == first.meta.id)
    }

    @Test("markAbandonedRecordingPaused closes the open segment and marks the session paused")
    func markAbandonedPausesRecordingSession() async throws {
        let (store, root) = makeStore()
        defer { try? FileManager.default.removeItem(at: root) }
        let created = try await store.createDraftSession(seed: .none)
        _ = try await store.beginRecording(created.meta.id)
        await store.abandonRecording(created.meta.id)

        try await store.markAbandonedRecordingPaused(created.meta.id)

        let handle = try await store.openSession(created.meta.id)
        let meta = await handle.meta
        #expect(meta.state == .paused)
        #expect(meta.recordings.count == 1)
        #expect(meta.recordings.last?.endedAt != nil)
    }

    @Test("markAbandonedRecordingPaused leaves a non-recording session untouched")
    func markAbandonedIgnoresNonRecording() async throws {
        let (store, root) = makeStore()
        defer { try? FileManager.default.removeItem(at: root) }
        let created = try await store.createDraftSession(seed: .none)

        try await store.markAbandonedRecordingPaused(created.meta.id)

        let handle = try await store.openSession(created.meta.id)
        let meta = await handle.meta
        #expect(meta.state == .draft)
        #expect(meta.recordings.isEmpty)
    }

    @Test("DraftMetaOverrides trims the title and drops titleAutoNamedOnce for blank titles")
    func overridesResolution() {
        #expect(DraftMetaOverrides.none.resolvedTitle == "")
        #expect(DraftMetaOverrides.none.resolvedTitleAutoNamedOnce == false)

        let padded = DraftMetaOverrides(title: "  Sync \n", titleAutoNamedOnce: true)
        #expect(padded.resolvedTitle == "Sync")
        #expect(padded.resolvedTitleAutoNamedOnce == true)

        let blank = DraftMetaOverrides(title: "   ", titleAutoNamedOnce: true)
        #expect(blank.resolvedTitle == "")
        #expect(blank.resolvedTitleAutoNamedOnce == false)
    }

    @Test("SessionMeta round-trips autoRecord and decodes legacy JSON without it as nil")
    func autoRecordCoding() throws {
        let auto = AutoRecordMeta(source: .googleMeet, meetingCode: "abc-defg-hij")
        let meta = SessionMeta(
            id: "2026-07-02T09-00-00_deadbeef",
            title: "",
            titleAutoGenerated: true,
            titleAutoNamedOnce: false,
            titleProposal: nil,
            state: .draft,
            createdAt: Date(timeIntervalSince1970: 1_751_000_000),
            startedAt: nil,
            endedAt: nil,
            durationMs: 0,
            basedOnSession: nil,
            autoRecord: auto,
            segmentCount: 0,
            refinedCount: 0,
            appVersion: "0.1.0"
        )
        let data = try SessionJSONCoding.makeEncoder().encode(meta)
        let decoded = try SessionJSONCoding.makeDecoder().decode(SessionMeta.self, from: data)
        #expect(decoded.autoRecord == auto)

        var object = try #require(JSONSerialization.jsonObject(with: data) as? [String: Any])
        let nested = try #require(object["autoRecord"] as? [String: Any] ?? object["auto_record"] as? [String: Any])
        #expect(nested["source"] as? String == "google_meet")

        object.removeValue(forKey: "autoRecord")
        object.removeValue(forKey: "auto_record")
        let legacy = try JSONSerialization.data(withJSONObject: object)
        let legacyDecoded = try SessionJSONCoding.makeDecoder().decode(SessionMeta.self, from: legacy)
        #expect(legacyDecoded.autoRecord == nil)
    }
}
