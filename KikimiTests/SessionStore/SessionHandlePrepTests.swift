import Foundation
import Testing

@testable import Kikimi

/// Unit tests for `SessionHandle+Prep.swift` (`docs/design/07-session-store.md` section 8 / kikimi.md
/// 4 章・7 章・8 章).
///
/// Session fixtures are written directly to disk with `SessionJSONCoding`/`FileManager` (bypassing
/// `SessionHandle`, mirroring `SessionStoreCrashRecoveryTests`'s "手動で用意した fixture" pattern), then
/// opened via `SessionStore(sessionsRootDirectory:).openSession(_:)` to obtain the `SessionHandle`
/// under test — the same test-only construction path `SessionStoreCrashRecoveryTests` uses, so these
/// tests don't need to know `SessionHandle`'s own initializer.
@Suite("SessionHandle+Prep")
struct SessionHandlePrepTests {
    private func makeTempRoot() -> URL {
        let url = FileManager.default.temporaryDirectory
            .appendingPathComponent("SessionHandlePrepTests-\(UUID().uuidString)", isDirectory: true)
        try? FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
        return url
    }

    private func baseMeta(id: String) -> SessionMeta {
        SessionMeta(
            id: id,
            title: "Test Session",
            titleAutoGenerated: true,
            titleAutoNamedOnce: false,
            titleProposal: nil,
            state: .draft,
            createdAt: Date(timeIntervalSince1970: 1_751_000_000),
            startedAt: nil,
            endedAt: nil,
            durationMs: 0,
            basedOnSession: nil,
            segmentCount: 0,
            refinedCount: 0,
            appVersion: "0.1.0"
        )
    }

    /// Writes `meta.json` for a session directly to disk, creating the session folder if needed.
    @discardableResult
    private func writeFixtureSession(root: URL, id: String) throws -> URL {
        let sessionDirectory = root.appendingPathComponent(id, isDirectory: true)
        try FileManager.default.createDirectory(at: sessionDirectory, withIntermediateDirectories: true)
        let data = try SessionJSONCoding.makeEncoder().encode(baseMeta(id: id))
        try data.write(to: sessionDirectory.appendingPathComponent("meta.json"), options: [.atomic])
        return sessionDirectory
    }

    private func readFile(_ name: String, in directory: URL) -> String? {
        try? String(contentsOf: directory.appendingPathComponent(name), encoding: .utf8)
    }

    // MARK: - readContext / writeContext

    @Test("readContext returns an empty string when context.md does not exist")
    func readContextReturnsEmptyWhenMissing() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "session-a")

        let store = SessionStore(sessionsRootDirectory: root)
        let handle = try await store.openSession("session-a")

        #expect(await handle.readContext() == "")
    }

    @Test("writeContext then readContext round-trips the exact content")
    func writeThenReadContextRoundTrips() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        let sessionDirectory = try writeFixtureSession(root: root, id: "session-a")

        let store = SessionStore(sessionsRootDirectory: root)
        let handle = try await store.openSession("session-a")

        let content = "# 参加者\n- 田中さん、佐藤さん\n# アジェンダ\n- 見積提示"
        try await handle.writeContext(content)

        #expect(await handle.readContext() == content)
        #expect(readFile("context.md", in: sessionDirectory) == content)
    }

    @Test("writeContext saves content exceeding the 32KB limit in full rather than truncating")
    func writeContextDoesNotTruncateOversizedContent() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "session-a")

        let store = SessionStore(sessionsRootDirectory: root)
        let handle = try await store.openSession("session-a")

        let oversized = String(repeating: "a", count: 40 * 1_024)
        try await handle.writeContext(oversized)

        let readBack = await handle.readContext()
        #expect(readBack == oversized)
        #expect(readBack.utf8.count == 40 * 1_024)
    }

    // MARK: - readSummaryTemplate / writeSummaryTemplate

    @Test("readSummaryTemplate falls back to the built-in default template when summary_template.md does not exist")
    func readSummaryTemplateFallsBackWhenMissing() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "session-a")

        let store = SessionStore(sessionsRootDirectory: root)
        let handle = try await store.openSession("session-a")

        #expect(await handle.readSummaryTemplate() == SessionHandle.defaultSummaryTemplate)
    }

    @Test("the built-in default template contains the schema fields kikimi.md 8 章 documents")
    func defaultSummaryTemplateContainsSchemaFields() {
        let template = SessionHandle.defaultSummaryTemplate
        #expect(template.contains("{{title}}"))
        #expect(template.contains("{{overview}}"))
        #expect(template.contains("{{#participants}}"))
        #expect(template.contains("{{#decisions}}"))
        #expect(template.contains("{{#action_items}}"))
    }

    @Test("writeSummaryTemplate then readSummaryTemplate round-trips the exact content")
    func writeThenReadSummaryTemplateRoundTrips() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        let sessionDirectory = try writeFixtureSession(root: root, id: "session-a")

        let store = SessionStore(sessionsRootDirectory: root)
        let handle = try await store.openSession("session-a")

        let content = "# {{title}}\n## ヒアリング内容\n## 提示した見積"
        try await handle.writeSummaryTemplate(content)

        #expect(await handle.readSummaryTemplate() == content)
        #expect(readFile("summary_template.md", in: sessionDirectory) == content)
    }

    @Test("writeSummaryTemplate saves content exceeding the 16KB limit in full rather than truncating")
    func writeSummaryTemplateDoesNotTruncateOversizedContent() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "session-a")

        let store = SessionStore(sessionsRootDirectory: root)
        let handle = try await store.openSession("session-a")

        let oversized = String(repeating: "b", count: 20 * 1_024)
        try await handle.writeSummaryTemplate(oversized)

        let readBack = await handle.readSummaryTemplate()
        #expect(readBack == oversized)
        #expect(readBack.utf8.count == 20 * 1_024)
    }

    // MARK: - copyPrepFiles

    @Test("copyPrepFiles(scope: .contextOnly) copies only context.md, leaving summary_template.md untouched")
    func copyPrepFilesContextOnly() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "source")
        try writeFixtureSession(root: root, id: "target")

        let store = SessionStore(sessionsRootDirectory: root)
        let source = try await store.openSession("source")
        let target = try await store.openSession("target")

        try await source.writeContext("source context")
        try await source.writeSummaryTemplate("source template")
        try await target.writeSummaryTemplate("target's own template")

        try await target.copyPrepFiles(from: "source", scope: .contextOnly)

        #expect(await target.readContext() == "source context")
        #expect(await target.readSummaryTemplate() == "target's own template")
    }

    @Test("copyPrepFiles(scope: .templateOnly) copies only summary_template.md, leaving context.md untouched")
    func copyPrepFilesTemplateOnly() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "source")
        try writeFixtureSession(root: root, id: "target")

        let store = SessionStore(sessionsRootDirectory: root)
        let source = try await store.openSession("source")
        let target = try await store.openSession("target")

        try await source.writeContext("source context")
        try await source.writeSummaryTemplate("source template")
        try await target.writeContext("target's own context")

        try await target.copyPrepFiles(from: "source", scope: .templateOnly)

        #expect(await target.readContext() == "target's own context")
        #expect(await target.readSummaryTemplate() == "source template")
    }

    @Test("copyPrepFiles(scope: .both) overwrites both context.md and summary_template.md")
    func copyPrepFilesBoth() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "source")
        try writeFixtureSession(root: root, id: "target")

        let store = SessionStore(sessionsRootDirectory: root)
        let source = try await store.openSession("source")
        let target = try await store.openSession("target")

        try await source.writeContext("source context")
        try await source.writeSummaryTemplate("source template")
        try await target.writeContext("target's own context")
        try await target.writeSummaryTemplate("target's own template")

        try await target.copyPrepFiles(from: "source", scope: .both)

        #expect(await target.readContext() == "source context")
        #expect(await target.readSummaryTemplate() == "source template")
    }

    @Test("copyPrepFiles falls back to the global defaults when the source session's files don't exist")
    func copyPrepFilesFallsBackWhenSourceFilesMissing() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        // Source session folder exists (has meta.json) but was never given context.md/summary_template.md.
        try writeFixtureSession(root: root, id: "source")
        try writeFixtureSession(root: root, id: "target")

        let store = SessionStore(sessionsRootDirectory: root)
        let target = try await store.openSession("target")
        try await target.writeContext("target's own context")
        try await target.writeSummaryTemplate("target's own template")

        try await target.copyPrepFiles(from: "source", scope: .both)

        #expect(await target.readContext() == "")
        #expect(await target.readSummaryTemplate() == SessionHandle.defaultSummaryTemplate)
    }

    @Test("copyPrepFiles falls back to the global defaults when the source session has no folder on disk at all")
    func copyPrepFilesFallsBackWhenSourceSessionDoesNotExist() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "target")

        let store = SessionStore(sessionsRootDirectory: root)
        let target = try await store.openSession("target")
        try await target.writeContext("target's own context")
        try await target.writeSummaryTemplate("target's own template")

        try await target.copyPrepFiles(from: "does-not-exist", scope: .both)

        #expect(await target.readContext() == "")
        #expect(await target.readSummaryTemplate() == SessionHandle.defaultSummaryTemplate)
    }

    @Test("copyPrepFiles rejects a sourceSessionId that would escape sessionsRootDirectory")
    func copyPrepFilesRejectsPathTraversal() async throws {
        let root = makeTempRoot()
        defer { try? FileManager.default.removeItem(at: root) }
        try writeFixtureSession(root: root, id: "target")

        let store = SessionStore(sessionsRootDirectory: root)
        let target = try await store.openSession("target")

        await #expect(throws: SessionStoreError.invalidSessionId("../../etc")) {
            try await target.copyPrepFiles(from: "../../etc", scope: .both)
        }
    }
}
