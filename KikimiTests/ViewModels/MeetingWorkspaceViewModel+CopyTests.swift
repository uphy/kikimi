// MARK: - DateFormatter.hhmmss

/// Shared `HH:mm:ss` formatter matching `TranscriptMarkdownRenderer`'s own private `timeFormatter`
/// (`Kikimi/Markdown/TranscriptMarkdownRenderer.swift`) exactly, so this file's assertions compute
/// expected times the same way the renderer does, without reaching into that `private` formatter.
private extension DateFormatter {
    static let hhmmss: DateFormatter = {
        let formatter = DateFormatter()
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.timeZone = .current
        formatter.dateFormat = "HH:mm:ss"
        return formatter
    }()
}
