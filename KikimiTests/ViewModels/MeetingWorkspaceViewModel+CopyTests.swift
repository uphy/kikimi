        #expect(pasteboard.writtenStrings.count == 1, "the write is still attempted")
        #expect(viewModel.copyFeedbackToken == 0, "a failed write must not bump copyFeedbackToken")
        #expect(viewModel.copyFeedbackRowId == nil)
    }

    @Test("copyRowMarkdown(rowId:) does not set copyFeedbackRowId when the pasteboard write fails")
    func copyRowMarkdownDoesNotUpdateFeedbackOnPasteboardFailure() async throws {
        let root = makeTemporaryDirectory(prefix: "MeetingWorkspaceViewModelCopyTests-f2")
        defer { try? FileManager.default.removeItem(at: root) }
        let handle = SessionHandle(directoryURL: root, meta: makeSessionMeta())
        let pasteboard = FakePasteboard()
        pasteboard.writeResult = false
